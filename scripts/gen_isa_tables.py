#!/usr/bin/env python3
"""Generate ISA tables for pyrlyn-jit validation from AsmJit's instruction database.

Reads third_party/asmjit/db/isa_x86.json and isa_aarch64.json (AsmJit `db/`), picks the forms that
pyrlyn-jit implements, and writes:
  src/x86_64/isa.zig   - per instruction: AsmJit signature, encoding, opcode bytes, ModRM digit,
                         immediate kind, required CPU features; full x86 feature enum.
  src/aarch64/isa.zig  - per instruction: AsmJit signature, fixed-bit mask/value, which register
                         fields accept SP, immediate field width/scale, required features.
The generator fails if a form pyrlyn-jit emits is missing from the database.

    python3 scripts/gen_isa_tables.py      # then: zig build test
"""
import json, os, re, subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DB = os.path.join(ROOT, "third_party", "asmjit", "db")
ALU = ["add", "or", "adc", "sbb", "and", "sub", "xor", "cmp"]
CC = ["o", "no", "b", "ae", "e", "ne", "be", "a", "s", "ns", "p", "np", "l", "ge", "le", "g"]


def zstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


# ---------------------------------------------------------------- x86 ----
def x86_entries():
    d = json.load(open(os.path.join(DB, "isa_x86.json")))
    for g in d["instructions"]:
        for i in g["instructions"]:
            enc = i.get("x64") or i.get("any")
            if not enc:
                continue
            text = re.sub(r"^(\[[a-z_]+\] )+", "", i["inst"])
            mn = text.split(" ")[0]
            ext = i.get("ext") or g.get("ext") or ""
            yield mn, text, enc, [e for e in ext.split() if e]


def x86_features():
    feats = set()
    for _, _, _, ext in x86_entries():
        feats.update(ext)
    return sorted(feats)


def x86_find(mn_re, enc_re):
    out = []
    for mn, text, enc, ext in x86_entries():
        if re.fullmatch(mn_re, mn) and re.search(enc_re, enc):
            out.append((text, enc, ext))
    if not out:
        raise SystemExit(f"x86: no AsmJit form for {mn_re} / {enc_re}")
    return out[0]


def x86_form(text, enc, ext):
    body = enc.split(":", 1)[1].split()
    opcode, plus, digit, imm = [], "none", "null", "none"
    for t in body:
        if t in ("REX.W",):
            continue
        m = re.fullmatch(r"([0-9A-F]{2})\+r", t)
        if m:
            opcode.append(int(m.group(1), 16)); plus = "reg"; continue
        if re.fullmatch(r"[0-9A-F]{2}", t):
            opcode.append(int(t, 16)); continue
        m = re.fullmatch(r"/([0-7])", t)
        if m:
            digit = m.group(1); continue
        if t == "/r":
            digit = "null"; continue
        imm = {"ib": "imm8", "iv": "imm32", "id": "imm32", "iq": "imm64", "cb": "rel8", "cd": "rel32"}.get(t, imm)
    modrm = "/" in enc
    ops = ", ".join(f"0x{b:02X}" for b in opcode)
    feats = ", ".join(f'.@"{e}"' for e in ext)
    return (f".{{ .asmjit = {zstr(text)}, .enc = {zstr(enc.strip())}, .opcode = &.{{ {ops} }}, "
            f".plus = .{plus}, .modrm = {str(modrm).lower()}, .digit = {digit}, .imm = .{imm}, "
            f".features = &.{{ {feats} }} }}")


def gen_x86():
    f = lambda m, e: x86_form(*x86_find(m, e))
    single = {
        "mov_rr": [f("mov", r"89 /r")], "mov_mr": [f("mov", r"89 /r")], "mov_rm": [f("mov", r"8B /r")],
        "mov_mi": [f("mov", r"C7 /0 iv")], "lea": [f("lea", r"REX.W 8D /r")],
        "mov_ri": [f("mov", r"^op : B8\+r id"), f("mov", r"C7 /0 iv"), f("mov", r"REX.W B8\+r iq")],
        "movabs": [f("movabs", r"REX.W B8\+r iq")],
        "test_rr": [f("test", r"85 /r")], "imul_rr": [f("imul", r"0F AF /r")], "imul_rm": [f("imul", r"0F AF /r")],
        "imul_rri": [f("imul", r"6B /r ib"), f("imul", r"69 /r iv")],
        "push": [f("push", r"^op : 50\+r")], "pop": [f("pop", r"^op : 58\+r")],
        "ret": [f("ret", r"^op : C3$")], "nop": [f("nop", r"^op : 90$")],
        "call_r": [f("call", r"FF /2")], "jmp_r": [f("jmp", r"FF /4")],
        "jmp": [f("jmp", r"EB cb"), f("jmp", r"E9 cd")], "call": [f("call", r"E8 cd")],
    }
    alu = {
        "alu_rr": lambda i, n: [f(n, rf"(REX.W {i*8+1:02X} /r|^mr : {i*8+1:02X} /r)")],
        "alu_mr": lambda i, n: [f(n, rf"\b{i*8+1:02X} /r")],
        "alu_rm": lambda i, n: [f(n, rf"\b{i*8+3:02X} /r")],
        "alu_ri": lambda i, n: [f(n, rf"(REX.W 83 /{i} ib|^m  : 83 /{i} ib)"), f(n, rf"(REX.W 81 /{i} id|81 /{i} iv)"),
                                f(n, rf"(REX.W {i*8+5:02X} id|^op : {i*8+5:02X} iv)")],
    }
    out = ["//! GENERATED by scripts/gen_isa_tables.py from AsmJit db/isa_x86.json — do not edit.",
           "//! Forms pyrlyn-jit emits for each instruction, with encodings and required CPU features.",
           'const std = @import("std");', "",
           "/// Every CPU feature (`ext`) named in AsmJit's x86 database.",
           "pub const Feature = enum {"]
    out += [f'    @"{e}",' for e in x86_features()]
    out += ["};", "pub const Features = std.EnumSet(Feature);", "",
            "/// Set of features from a list (comptime-friendly).",
            "pub fn featureSet(comptime list: []const Feature) Features {",
            "    @setEvalBranchQuota(100_000);",
            "    var s: Features = .empty;",
            "    for (list) |f| s.insert(f);",
            "    return s;",
            "}", "",
            "pub const Plus = enum { none, reg };",
            "pub const Imm = enum { none, imm8, imm32, imm64, rel8, rel32 };",
            "pub const Form = struct {",
            "    asmjit: []const u8,", "    enc: []const u8,", "    opcode: []const u8,",
            "    plus: Plus,", "    modrm: bool,", "    digit: ?u3,", "    imm: Imm,", "    features: []const Feature,",
            "};", "", "pub const table = struct {"]
    for k, v in single.items():
        out.append(f"    pub const {k} = [_]Form{{ " + ", ".join(v) + " };")
    for k, fn in alu.items():
        out.append(f"    pub const {k} = [8][]const Form{{")
        for i, n in enumerate(ALU):
            out.append("        &.{ " + ", ".join(fn(i, n)) + " },")
        out.append("    };")
    out.append("    pub const jcc = [16][]const Form{")
    for i, c in enumerate(CC):
        out.append("        &.{ " + f("j[a-z]+", rf"^op : {0x70+i:02X} cb") + ", " + f("j[a-z]+", rf"^op : 0F {0x80+i:02X} cd") + " },")
    out += ["    };", "};", ""]
    return "\n".join(out)


# ------------------------------------------------------------ aarch64 ----
def a64_entries():
    d = json.load(open(os.path.join(DB, "isa_aarch64.json")))
    for g in d["instructions"]:
        ext = g.get("ext", "")
        for i in g.get("data", []):
            yield i["inst"], i.get("op", ""), [e for e in ext.split() if e]


def a64_features():
    feats = set()
    for _, _, ext in a64_entries():
        feats.update(ext)
    return sorted(feats)


# Known database issues (AsmJit 0464e1c), fixed here and verified by the LLVM-generated tests:
# - `cbz Xn` carries the cbnz bit pattern (bit 24 = 1); CBZ is 0xB4000000.
# - `ret Xn` has bit 25 = 0 (0xD45F0000); RET is 0xD65F0000.
A64_OP_OVERRIDE = {
    "cbz Xn, #relS*4": "10110100|relS:19|Rn",
    "ret Xn": "11010110|010|11111|0|00000|Rn|00000",
    "and Xd|SP, Xn, Xm, {sop #n}": "10001010|sop:2|0|Rm|n:6|Rn|Rd",
}
# - `and Xd|SP, Xn, Xm` (shifted register): Rd = 31 is XZR, not SP; `sop` is 2 bits.
A64_SIG_FIX = {"and Xd|SP, Xn, Xm, {sop #n}": "and Xd, Xn, Xm, {sop #n}"}


def a64_form(sig):
    for text, op, ext in a64_entries():
        if text == sig:
            op = A64_OP_OVERRIDE.get(text, op)
            break
    else:
        raise SystemExit(f"aarch64: no AsmJit form {sig!r}")
    text = A64_SIG_FIX.get(text, text)
    mask = value = 0
    pos = 32
    imm_bits = 0
    for t in op.split("|"):
        if re.fullmatch(r"[01]+", t):
            n = len(t); pos -= n
            mask |= ((1 << n) - 1) << pos
            value |= int(t, 2) << pos
            continue
        m = re.fullmatch(r"([A-Za-z]+)(?::(\d+))?", t)
        n = int(m.group(2)) if m.group(2) else (5 if m.group(1) in ("Rd", "Rn", "Rm", "Ra", "Rs", "Rt") else 4)
        if m.group(1) in ("imm", "immZ", "offZ", "relS"):
            imm_bits = n
        pos -= n
    assert pos == 0, (sig, op, pos)
    scale = int(re.search(r"\*(\d+)", text).group(1)) if re.search(r"#(off|rel)\w*\*(\d+)", text) else 1
    rd_sp = "d|SP" in text
    rn_sp = "n|SP" in text
    feats = ", ".join(f'.@"{e}"' for e in ext)
    return (f".{{ .asmjit = {zstr(text)}, .op = {zstr(op)}, .mask = 0x{mask:08X}, .value = 0x{value:08X}, "
            f".rd_sp = {str(rd_sp).lower()}, .rn_sp = {str(rn_sp).lower()}, .imm_bits = {imm_bits}, .imm_scale = {scale}, "
            f".features = &.{{ {feats} }} }}")


def gen_a64():
    m = {
        "movz": "movz Xd, #imm, {lsl #n}", "movk": "movk Xd, #imm, {lsl #n}", "mov": "mov Xd, Xm",
        "add": "add Xd, Xn, Xm, {lsl|lsr|asr #n}", "sub": "sub Xd, Xn, Xm, {lsl|lsr|asr #n}", "mul": "mul Xd, Xn, Xm",
        "add_imm": "add Xd|SP, Xn|SP, #immZ, {lsl #n=0|12}", "sub_imm": "sub Xd|SP, Xn|SP, #immZ, {lsl #n=0|12}",
        "cmp": "cmp Xn, Xm, {lsl|lsr|asr #n}", "cmp_imm": "cmp Xn|SP, #imm, {lsl #n=0|12}",
        "ldr": "ldr Xd, [Xn|SP, #offZ*8]", "str": "str Xs, [Xn|SP, #offZ*8]",
        "ret": "ret Xn", "blr": "blr Xn", "b": "b #relS*4", "bl": "bl #relS*4", "bcond": "b.<cond> #relS*4",
        "cbz": "cbz Xn, #relS*4", "cbnz": "cbnz Xn, #relS*4",
        "sdiv": "sdiv Xd, Xn, Xm", "udiv": "udiv Xd, Xn, Xm", "madd": "madd Xd, Xn, Xm, Xa", "msub": "msub Xd, Xn, Xm, Xa",
        "mneg": "mneg Xd, Xn, Xm", "smulh": "smulh Xd, Xn, Xm", "umulh": "umulh Xd, Xn, Xm",
        "neg": "neg Xd, Xm, {lsl|lsr|asr #n}", "and_": "and Xd|SP, Xn, Xm, {sop #n}", "orr": "orr Xd, Xn, Xm, {sop #n}",
        "eor": "eor Xd, Xn, Xm, {sop #n}", "csel": "csel Xd, Xn, Xm, #cond", "cset": "cset Xd, #cond",
        "lsl_imm": "lsl Xd, Xn, #n", "lsr_imm": "lsr Xd, Xn, #n", "asr_imm": "asr Xd, Xn, #n",
    }
    out = ["//! GENERATED by scripts/gen_isa_tables.py from AsmJit db/isa_aarch64.json — do not edit.",
           'const std = @import("std");', "",
           "/// Every CPU feature (`ext`) named in AsmJit's AArch64 database.",
           "pub const Feature = enum {"]
    out += [f'    @"{e}",' for e in a64_features()]
    out += ["};", "pub const Features = std.EnumSet(Feature);", "",
            "/// Set of features from a list (comptime-friendly).",
            "pub fn featureSet(comptime list: []const Feature) Features {",
            "    @setEvalBranchQuota(100_000);",
            "    var s: Features = .empty;",
            "    for (list) |f| s.insert(f);",
            "    return s;",
            "}", "",
            "pub const Form = struct {",
            "    asmjit: []const u8,", "    op: []const u8,",
            "    /// Fixed bits of the encoding: `(word & mask) == value` for a correct encoding.",
            "    mask: u32,", "    value: u32,",
            "    /// Register 31 in Rd / Rn means SP (otherwise XZR).",
            "    rd_sp: bool,", "    rn_sp: bool,",
            "    /// Width of the immediate/offset/displacement field and its scale (bytes per unit).",
            "    imm_bits: u8,", "    imm_scale: u8,", "    features: []const Feature,",
            "};", "", "pub const table = struct {"]
    for k, sig in m.items():
        out.append(f"    pub const {k}: Form = {a64_form(sig)};")
    out += ["};", ""]
    return "\n".join(out)


def write(path, text):
    with open(os.path.join(ROOT, path), "w") as fp:
        fp.write(text)
    subprocess.run(["zig", "fmt", os.path.join(ROOT, path)], check=False)
    print("wrote", path)


write("src/x86_64/isa.zig", gen_x86())
write("src/aarch64/isa.zig", gen_a64())
