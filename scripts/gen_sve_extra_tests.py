#!/usr/bin/env python3
"""Hand-written LLVM-oracle cases for the SVE/SME forms whose DB syntax the generic generator
(scripts/gen_sve_tests.py) cannot spell in a way LLVM accepts (bench/a64_sve_coverage.txt).
Each case is real LLVM syntax plus the matching pyrlyn-jit operands; the expected word comes from
the system clang + objdump. Writes src/a64_sve_extra_tests.zig.

    python3 scripts/gen_sve_extra_tests.py
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_sve_tests as s

MARCH_EXTRA = "+f32mm"
Z = lambda i, t: f"a64.zreg({i}, .{t})"
ZE = lambda i, t, k: f"a64.zelem({i}, .{t}, {k})"
P = lambda i, t: f"a64.preg({i}, .{t})"
PM, PZ, PG = "a64.pmerge(1)", "a64.pzero(1)", "a64.preg(1, .none)"
I = lambda v: f"a64.imm({v})"
F = lambda v: f"a64.fimm({v})"
SC = lambda k, i: f"a64.scalar(.{k}, {i})"
LSL8 = "a64.shift(.lsl, 8)"
TS = "bhsd"
WIDE = [("h", "b"), ("s", "h"), ("d", "s")]

def cases():
    c = []
    add = lambda mn, txt, *ops: c.append((mn, txt, list(ops)))
    for mn in ("add", "sub", "subr", "sqadd", "sqsub", "uqadd", "uqsub"):
        add(mn, f"{mn} z1.b, z1.b, #255", Z(1, "b"), Z(1, "b"), I(255))
        for t in "hsd":
            add(mn, f"{mn} z1.{t}, z1.{t}, #2, lsl #8", Z(1, t), Z(1, t), I(2), LSL8)
            add(mn, f"{mn} z1.{t}, z1.{t}, #7", Z(1, t), Z(1, t), I(7))
    for mn in ("brkas", "brkbs"):
        add(mn, f"{mn} p1.b, p2/z, p3.b", P(1, "b"), "a64.pzero(2)", P(3, "b"))
    for mn in ("clasta", "clastb"):
        for t in TS:
            add(mn, f"{mn} {t}1, p1, {t}1, z2.{t}", SC(t, 1), PG, SC(t, 1), Z(2, t))
    for t in TS:
        add("eorv", f"eorv {t}1, p1, z2.{t}", SC(t, 1), PG, Z(2, t))
        add("cpy", f"cpy z1.{t}, p1/m, #-1", Z(1, t), PM, I(-1))
        add("cpy", f"cpy z1.{t}, p1/z, #127", Z(1, t), PZ, I(127))
        for mn in ("dup", "mov"):
            add(mn, f"{mn} z1.{t}, #-128", Z(1, t), I(-128))
            r = "x" if t == "d" else "w"
            add(mn, f"{mn} z1.{t}, {'sp' if t == 'd' else 'wsp'}", Z(1, t), "a64.sp" if t == "d" else "a64.wsp")
            add(mn, f"{mn} z1.{t}, {r}3", Z(1, t), f"a64.{r}(3)")
        if t != "b":
            add("cpy", f"cpy z1.{t}, p1/m, #3, lsl #8", Z(1, t), PM, I(3), LSL8)
            for mn in ("dup", "mov"):
                add(mn, f"{mn} z1.{t}, #3, lsl #8", Z(1, t), I(3), LSL8)
    for t in "hsd":
        for mn in ("fcmeq", "fcmge", "fcmgt", "fcmle", "fcmlt", "fcmne"):
            add(mn, f"{mn} p2.{t}, p1/z, z1.{t}, #0.0", P(2, t), PZ, Z(1, t), F(0.0))
        for mn, vals in (("fmax", (0.0, 1.0)), ("fmaxnm", (0.0, 1.0)), ("fmin", (0.0, 1.0)), ("fminnm", (0.0, 1.0)), ("fmul", (0.5, 2.0))):
            for v in vals:
                add(mn, f"{mn} z1.{t}, p1/m, z1.{t}, #{v}", Z(1, t), PM, Z(1, t), F(v))
    add("fmmla", "fmmla z1.s, z2.s, z3.s", Z(1, "s"), Z(2, "s"), Z(3, "s"))
    for mn in ("saddwb", "saddwt", "ssubwb", "ssubwt", "uaddwb", "uaddwt", "usubwb", "usubwt"):
        for a, b in WIDE:
            add(mn, f"{mn} z1.{a}, z2.{a}, z3.{b}", Z(1, a), Z(2, a), Z(3, b))
    for a, b in WIDE:
        bits = {"b": 8, "h": 16, "s": 32}[b]
        for mn in ("shrnb", "shrnt"):
            add(mn, f"{mn} z1.{b}, z2.{a}, #1", Z(1, b), Z(2, a), I(1))
            add(mn, f"{mn} z1.{b}, z2.{a}, #{bits}", Z(1, b), Z(2, a), I(bits))
        for mn in ("sshllb", "sshllt", "ushllb", "ushllt"):
            add(mn, f"{mn} z1.{a}, z2.{b}, #0", Z(1, a), Z(2, b), I(0))
            add(mn, f"{mn} z1.{a}, z2.{b}, #{bits - 1}", Z(1, a), Z(2, b), I(bits - 1))
    for mn in ("sqdmullb", "sqdmullt"):
        add(mn, f"{mn} z1.s, z2.h, z3.h[7]", Z(1, "s"), Z(2, "h"), ZE(3, "h", 7))
        add(mn, f"{mn} z1.d, z2.s, z3.s[3]", Z(1, "d"), Z(2, "s"), ZE(3, "s", 3))
    for p in ("sq", "uq"):
        for d in ("inc", "dec"):
            for t in "hsd":
                mn = f"{p}{d}{ {'h': 'h', 's': 'w', 'd': 'd'}[t]}"
                add(mn, f"{mn} z1.{t}", Z(1, t))
                add(mn, f"{mn} z1.{t}, pow2", Z(1, t), I(0))
                add(mn, f"{mn} z1.{t}, vl8, mul #4", Z(1, t), I(8), I(4))
    return c

def main():
    s.MARCH += MARCH_EXTRA
    cs = cases()
    words = s.assemble([t for _, t, _ in cs])
    rejected = [t for _, t, _ in cs if t not in words]
    if rejected: raise SystemExit("LLVM rejected: " + "; ".join(rejected))
    out = ["//! GENERATED by scripts/gen_sve_extra_tests.py - do not edit. Hand-spelled LLVM-syntax cases for",
           f"//! the SVE forms listed in bench/a64_sve_coverage.txt; expected words from system clang ({len(cs)} cases).",
           'const std = @import("std");', 'const a64 = @import("aarch64/a64.zig");', "",
           "fn check(expected: u32, comptime mn: a64.Mnemonic, ops: []const a64.Op, text: []const u8) u32 {",
           "    const r = a64.encodeMnIdx(mn, ops) orelse {", '        std.debug.print("NoMatchingForm: {s}\\n", .{text});', "        return 1;", "    };",
           "    if (r.word == expected) return 0;",
           '    std.debug.print("encoding mismatch: {s}: want {X:0>8} got {X:0>8} form={s}#{d}\\n", .{ text, expected, r.word, @tagName(mn), r.idx });',
           "    return 1;", "}", "", 'test "SVE forms with hand-spelled LLVM syntax" {', "    var fails: u32 = 0;"]
    for mn, t, ops in cs:
        out.append(f'    fails += check(0x{words[t]:08X}, .@"{mn}", &.{{ {", ".join(ops)} }}, "{t}");')
    out += ["    try std.testing.expectEqual(@as(u32, 0), fails);", "}", ""]
    open(os.path.join(s.ROOT, "src/a64_sve_extra_tests.zig"), "w").write("\n".join(out))
    print(f"{len(cs)} cases")

if __name__ == "__main__":
    main()
