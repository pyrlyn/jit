#!/usr/bin/env python3
"""Writes src/avx512_tests.zig: AVX-512 forms through `x86_64.Assembler.vinst` (zmm/ymm/xmm
0..31, opmasks, zeroing, embedded broadcast, rounding/SAE, disp8*N boundaries) checked
byte-for-byte against LLVM (clang -c + objdump, see gen_gp_tests.assemble)."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_gp_tests import assemble

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def m(base, disp, size, idx=None, scale=1):
    sc = {1: "x1", 2: "x2", 4: "x4", 8: "x8"}[scale]
    z = f"x.ptrIdx(.{base}, .{idx}, .{sc}, {disp})" if idx else f"x.ptr(.{base}, {disp})"
    t = f"[{base}+{scale}*{idx}{disp:+d}]" if idx else f"[{base}{disp:+d}]"
    return f"v.mem({z}, {size})", t

SZ = {16: "xmmword", 32: "ymmword", 64: "zmmword", 4: "dword", 8: "qword"}
cases = []
def add(mn, zops, tops, extra="", text_suffix=""):
    cases.append((mn, zops, extra, f"{mn} {', '.join(tops)}{text_suffix}"))

R = lambda c, i: (f"v.{c}({i})", f"{c}{i}")
# Register banks incl. 16..31 at every vector length.
for c in ("xmm", "ymm", "zmm"):
    for d, s1, s2 in ((0, 1, 2), (16, 17, 31), (8, 24, 15), (31, 0, 16)):
        for mn in ("vaddps", "vpaddd", "vpxorq", "vmulpd"):
            a, b, cc = R(c, d), R(c, s1), R(c, s2)
            add(mn, [a[0], b[0], cc[0]], [a[1], b[1], cc[1]])
# Masks and zeroing.
for kk in (1, 7):
    for z in (False, True):
        a, b, cc = R("zmm", 3), R("zmm", 20), R("zmm", 5)
        ex = f".k = {kk}" + (", .z = true" if z else "")
        cases.append(("vaddps", [a[0], b[0], cc[0]], ex, f"vaddps {a[1]} {{k{kk}}}{' {z}' if z else ''}, {b[1]}, {cc[1]}"))
# Memory, disp8*N compression boundaries (N = 64 for zmm full, 4/8 for broadcast).
for disp in (0, 64, 8128, 8192, -8192, -8256, 63, 1):
    mz, mt = m("rax", disp, 64)
    add("vmovups", ["v.zmm(1)", mz], ["zmm1", f"zmmword ptr {mt}"])
    mz, mt = m("r12", disp, 64, "rcx", 4)
    add("vpaddd", ["v.zmm(17)", "v.zmm(2)", mz], ["zmm17", "zmm2", f"zmmword ptr {mt}"])
# Embedded broadcast.
for disp in (0, 4, 508, 512):
    mz, mt = m("rdi", disp, 4)
    cases.append(("vaddps", ["v.zmm(0)", "v.zmm(1)", f"v.bcst({mz}, 16)"], "", f"vaddps zmm0, zmm1, dword ptr {mt}{{1to16}}"))
    mz, mt = m("rdi", disp, 8)
    cases.append(("vmulpd", ["v.ymm(18)", "v.ymm(1)", f"v.bcst({mz}, 4)"], ".k = 2", f"vmulpd ymm18 {{k2}}, ymm1, qword ptr {mt}{{1to4}}"))
# Rounding / SAE.
for rc, t in (("rn", "rn-sae"), ("rd", "rd-sae"), ("ru", "ru-sae"), ("rz", "rz-sae")):
    cases.append(("vaddps", ["v.zmm(1)", "v.zmm(2)", "v.zmm(3)"], f".rc = .{rc}", f"vaddps zmm1, zmm2, zmm3, {{{t}}}"))
cases.append(("vmaxps", ["v.zmm(1)", "v.zmm(2)", "v.zmm(3)"], ".sae = true", "vmaxps zmm1, zmm2, zmm3, {sae}"))
# Compares into masks, mask ops, moves with masks, permutes, conversions.
add("vpcmpeqd", ["v.k(1)", "v.zmm(2)", "v.zmm(30)"], ["k1", "zmm2", "zmm30"])
add("vcmpps", ["v.k(3)", "v.zmm(2)", "v.zmm(3)", "1"], ["k3", "zmm2", "zmm3", "1"])
add("kandw", ["v.k(1)", "v.k(2)", "v.k(3)"], ["k1", "k2", "k3"])
add("kmovw", ["v.k(1)", "gp.r32(.rax)"], ["k1", "eax"])
add("vpermd", ["v.zmm(1)", "v.zmm(2)", "v.zmm(3)"], ["zmm1", "zmm2", "zmm3"])
add("vpternlogd", ["v.zmm(1)", "v.zmm(2)", "v.zmm(3)", "0xca"], ["zmm1", "zmm2", "zmm3", "0xca"])
add("vcvtdq2ps", ["v.zmm(1)", "v.zmm(25)"], ["zmm1", "zmm25"])
add("vextracti64x4", ["v.ymm(1)", "v.zmm(2)", "1"], ["ymm1", "zmm2", "1"])
add("vbroadcastss", ["v.zmm(9)", "v.xmm(1)"], ["zmm9", "xmm1"])
add("vpbroadcastd", ["v.zmm(9)", "gp.r32(.rcx)"], ["zmm9", "ecx"])
cases.append(("vmovdqu32", ["v.zmm(1)", m("rsi", 128, 64)[0]], ".k = 1, .z = true", f"vmovdqu32 zmm1 {{k1}} {{z}}, zmmword ptr {m('rsi', 128, 64)[1]}"))
cases.append(("vmovdqu64", [m("rsi", -64, 64)[0], "v.zmm(31)"], ".k = 4", f"vmovdqu64 zmmword ptr {m('rsi', -64, 64)[1]} {{k4}}, zmm31"))
mz, mt = m("rax", 0, 4)
cases.append(("vgatherdps", ["v.zmm(1)", "v.vsib(.rax, v.zmm(2), .x4, 0, 4)"], ".k = 1", "vgatherdps zmm1 {k1}, dword ptr [rax+4*zmm2]"))
cases.append(("vscatterdps", ["v.vsib(.rax, v.zmm(18), .x4, 64, 4)", "v.zmm(1)"], ".k = 2", "vscatterdps dword ptr [rax+4*zmm18+64] {k2}, zmm1"))

res = assemble([c[3] for c in cases])
missing = [c[3] for i, c in enumerate(cases) if i not in res]
if missing:
    raise SystemExit("LLVM rejected: " + "; ".join(missing))
out = ["//! GENERATED by scripts/gen_avx512_tests.py — do not edit. AVX-512 through",
       "//! `x86_64.Assembler.vinst`, expected bytes from LLVM (clang -c + objdump).",
       'const std = @import("std");', 'const opts = @import("pyrlyn_jit_options");',
       'const CodeBuffer = @import("core/code_buffer.zig").CodeBuffer;',
       'const x = @import("x86_64/assembler.zig");', "const v = x.vec;", 'const gp = @import("x86_64/gp.zig");', "",
       "fn check(cb: *CodeBuffer, expected: []const u8, text: []const u8) u32 {",
       "    defer cb.reset();",
       "    if (std.mem.eql(u8, expected, cb.code())) return 0;",
       '    std.debug.print("mismatch: {s}: expected {x}, got {x}\\n", .{ text, expected, cb.code() });',
       "    return 1;", "}", "",
       f'test "x86_64 AVX-512 via vinst: {len(cases)} forms byte-exact vs LLVM" {{',
       "    if (!opts.x86_64) return error.SkipZigTest;",
       "    var cb = CodeBuffer.init(std.testing.allocator);", "    defer cb.deinit();",
       "    const a = x.Assembler.init(&cb);", "    var fails: u32 = 0;"]
for i, (mn, zops, ex, txt) in enumerate(cases):
    bs = ", ".join(f"0x{b:02x}" for b in res[i])
    out.append(f"    try a.vinst(.{mn}, .{{ {', '.join(zops)} }}, .{{ {ex} }});")
    out.append(f'    fails += check(&cb, &.{{ {bs} }}, "{txt}");')
out += ["    try std.testing.expectEqual(@as(u32, 0), fails);", "}", "",
        'test "x86_64 AVX-512 via vinst: validation and hooks" {',
        "    if (!opts.x86_64) return error.SkipZigTest;",
        "    var cb = CodeBuffer.init(std.testing.allocator);", "    defer cb.deinit();",
        "    // xmm16+ do not exist in legacy SSE / VEX-only forms.",
        "    try std.testing.expect(std.meta.isError(x.Assembler.init(&cb).vinst(.addps, .{ v.xmm(16), v.xmm(1) }, .{})));",
        "    var h: x.CountingHooks = .{};",
        "    const ah = x.AssemblerT(.{ .Hooks = x.CountingHooks }).initHooks(&cb, &h);",
        "    try ah.vinst(.vaddps, .{ v.zmm(1), v.zmm(2), v.zmm(3) }, .{});",
        "    try std.testing.expectEqual(@as(usize, 1), h.instructions);",
        "    try std.testing.expectEqual(@as(usize, 6), h.bytes);", "}", ""]
open(os.path.join(ROOT, "src/avx512_tests.zig"), "w").write("\n".join(out))
print(f"{len(cases)} cases")
