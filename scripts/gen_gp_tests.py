#!/usr/bin/env python3
"""Generate src/gp_tests.zig: byte-exact tests for every generated GP form (scripts/gen_gp_tables.py).

For each form, a few operand instances (low/high registers, SIB/RBP/RIP memory, immediates) are
written as Intel-syntax assembly, assembled by LLVM (clang -c + objdump) and paired with the
equivalent `gp.emit` call. Lines LLVM rejects (AsmJit-only aliases) are dropped and counted.
"""
import json, os, re, subprocess, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GP = "rax rcx rdx rbx rsp rbp rsi rdi r8 r9 r10 r11 r12 r13 r14 r15".split()
N8 = "al cl dl bl spl bpl sil dil".split()
N16 = "ax cx dx bx sp bp si di".split()
N32 = "eax ecx edx ebx esp ebp esi edi".split()
ZK = {"and", "or", "test", "int", "out", "in"}


def rname(g, size):
    i = GP.index(g)
    if size == 64:
        return g
    if i >= 8:
        return g + {8: "b", 16: "w", 32: "d"}[size]
    return {8: N8, 16: N16, 32: N32}[size][i]


PTR = {8: "byte", 16: "word", 32: "dword", 64: "qword"}
ZSZ = {8: "byte", 16: "word", 32: "dword", 64: "qword"}
IMM = {"i8": 0x7F, "s8": -3, "u8": 200, "i16": 0x1234, "u16": 0xF234, "i32": 0x12345678, "s32": -0x12345,
       "u32": 0x89ABCDEF, "i64": 0x123456789AB, "one": 1}
FIXED = {"al": ("rax", 8), "ax": ("rax", 16), "eax": ("rax", 32), "rax": ("rax", 64), "cl": ("rcx", 8), "dx": ("rdx", 16)}
MEMS = [  # (zig base expr, asm text)
    ('x.ptrIdx(.rax, .rcx, .x2, 16)', "[rax+rcx*2+16]"),
    ('x.ptr(.r13, 0)', "[r13]"),
    ('x.ptrIdx(.r12, .r9, .x8, -0x1000)', "[r12+r9*8-4096]"),
]
REGSETS = [("rcx", "rdx"), ("r9", "r14"), ("rsi", "rdi")]  # third: sil/dil need REX in 8-bit


def instances(f, v):
    zs, ts = [], []
    gi = 0
    for k in f["ops"]:
        if k in ("r8", "r16", "r32", "r64"):
            g = REGSETS[v % 3][gi % 2]
            gi += 1
            sz = int(k[1:])
            zs.append(f"gp.r{sz}(.{g})")
            ts.append(rname(g, sz))
        elif k in ("m8", "m16", "m32", "m64", "m"):
            zm, tm = MEMS[v % 3]
            if v == 3:  # RIP-relative
                sz = int(k[1:]) if k != "m" else 0
                zs.append(f"gp.rip(0x100, .{ {0: 'none', 8: 'b', 16: 'w', 32: 'd', 64: 'q'}[sz] })")
                ts.append((f"{PTR[sz]} ptr " if sz else "") + "[rip+0x100]")
                continue
            if k == "m":
                zs.append(f"gp.mem({zm})")
                ts.append(tm)
            else:
                sz = int(k[1:])
                zs.append(f"gp.{ZSZ[sz]}({zm})")
                ts.append(f"{PTR[sz]} ptr {tm}")
        elif k in FIXED:
            g, sz = FIXED[k]
            zs.append(f"gp.r{sz}(.{g})")
            ts.append(rname(g, sz))
        else:
            val = IMM[k]
            zs.append(f"@as(i64, {val})")
            ts.append(str(val))
    return zs, ts


def assemble(lines):
    """Returns {index: bytes} for lines LLVM accepts."""
    keep = list(range(len(lines)))
    while True:
        with tempfile.TemporaryDirectory() as d:
            src, obj = os.path.join(d, "t.s"), os.path.join(d, "t.o")
            open(src, "w").write(".intel_syntax noprefix\n" + "\n".join(lines[i] for i in keep) + "\n")
            r = subprocess.run(["clang", "-c", "-target", "x86_64-apple-macos", src, "-o", obj], capture_output=True, text=True)
            if r.returncode != 0:
                bad = {int(m) - 2 for m in re.findall(r"t\.s:(\d+):\d+: error", r.stderr)}
                if not bad:
                    raise SystemExit(r.stderr)
                keep = [k for j, k in enumerate(keep) if j not in bad]
                continue
            out = subprocess.run(["objdump", "-d", obj], check=True, capture_output=True, text=True).stdout
        res = []
        for ln in out.splitlines():
            m = re.match(r"\s*[0-9a-f]+:((?:\s[0-9a-f]{2}(?=\s))+)", ln)
            if m:
                res.append([int(b, 16) for b in m.group(1).split()])
        assert len(res) == len(keep), (len(res), len(keep))
        return dict(zip(keep, res))


def main():
    fs = json.load(open(os.path.join(ROOT, "scripts/.gp_forms.json")))
    cases = []
    for mn in sorted(fs):
        for f in fs[mn]:
            has_mem = any(k.startswith("m") for k in f["ops"])
            for v in range(4 if has_mem else 3):
                zs, ts = instances(f, v)
                cases.append((mn, zs, f"{mn} {', '.join(ts)}".strip()))
    # de-dup identical text
    seen, uniq = set(), []
    for c in cases:
        if c[2] not in seen:
            seen.add(c[2])
            uniq.append(c)
    got = assemble([c[2] for c in uniq])
    out = ["//! GENERATED by scripts/gen_gp_tests.py — do not edit. Expected bytes from LLVM (clang -c + objdump).",
           f"//! {len(got)} cases accepted by LLVM, {len(uniq) - len(got)} AsmJit-only spellings skipped.",
           'const std = @import("std");', 'const opts = @import("zigjit_options");',
           'const CodeBuffer = @import("core/code_buffer.zig").CodeBuffer;', "",
           "/// Returns 1 on failure (printed), so one test reports every mismatching case.",
           "fn check(expected: []const u8, comptime mn: anytype, args: anytype, text: []const u8) u32 {",
           '    const gp = @import("x86_64/gp.zig");',
           "    var cb = CodeBuffer.init(std.testing.allocator);", "    defer cb.deinit();",
           "    gp.emit(&cb, mn, args) catch |e| {", '        std.debug.print("{s}: {s}\\n", .{ @errorName(e), text });', "        return 1;", "    };",
           "    if (std.mem.eql(u8, expected, cb.code())) return 0;",
           '    std.debug.print("encoding mismatch: {s}: expected {x}, got {x}\\n", .{ text, expected, cb.code() });', "    return 1;", "}", ""]
    items = sorted(got.items())
    chunk = 400
    for ci in range(0, len(items), chunk):
        part = items[ci:ci + chunk]
        out.append(f'test "x86_64 gp forms vs LLVM ({ci}..{ci + len(part)})" {{')
        out.append("    if (!opts.x86_64) return error.SkipZigTest;")
        out.append("    @setEvalBranchQuota(1_000_000);")
        out.append('    const x = @import("x86_64/assembler.zig");')
        out.append('    const gp = @import("x86_64/gp.zig");')
        out.append("    var fails: u32 = 0;")
        for i, b in part:
            mn, zs, text = uniq[i]
            m = f'@"{mn}"' if mn in ZK else mn
            hexs = ", ".join(f"0x{x:02X}" for x in b)
            out.append(f'    fails += check(&.{{ {hexs} }}, .{m}, .{{ {", ".join(zs)} }}, "{text}");')
        out.append("    _ = &x;")
        out.append("    try std.testing.expectEqual(@as(u32, 0), fails);")
        out.append("}")
        out.append("")
    open(os.path.join(ROOT, "src/gp_tests.zig"), "w").write("\n".join(out))
    print(f"{len(got)} cases, {len(uniq) - len(got)} skipped by LLVM")


if __name__ == "__main__":
    main()
