#!/usr/bin/env python3
"""Generate src/a64_table_tests.zig from src/testdata/a64_table_cases.txt.

    python3 scripts/gen_a64_table_tests.py [--verify]

The case file pins the LLVM-generated AArch64 table (src/aarch64/a64_table.zig) against the
AsmJit table it replaced: `asmjit` cases are AsmJit-table encodings the new table reproduces
byte for byte, `llvm` cases are encodings checked with llvm-mc, and `removed` cases are operand
combinations the old table accepted but LLVM's assembler rejects (they must be NoMatchingForm).
With --verify, every `llvm` case is re-assembled with llvm-mc and every `removed` case must be
rejected by it (LLVM_MC, default llvm-mc on PATH).
"""
import os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CASES = os.path.join(ROOT, "src/testdata/a64_table_cases.txt")
OUT = os.path.join(ROOT, "src/a64_table_tests.zig")
CHUNK = 400


def gp(i, sz):
    return ".{ .id = %s, .x = %s }" % (i, "true" if sz == "x" else "false")


def op(t):
    p = t.split(":")
    k = p[0]
    if k == "r":
        return ".{ .r = %s }" % gp(p[1], p[2])
    if k == "v":
        idx = "" if p[5] == "-1" else ", .idx = %s" % p[5]
        return ".{ .v = .{ .id = %s, .kind = .%s, .arr = .%s, .et = .%s%s } }" % (p[1], p[2], p[3], p[4], idx)
    if k == "i":
        return ".{ .imm = %s }" % p[1]
    if k == "f":
        return ".{ .fimm = %s }" % p[1]
    if k == "s":
        return ".{ .shift = .{ .op = .%s, .n = %s } }" % (p[1], p[2])
    if k == "c":
        return ".{ .cond = %s }" % p[1]
    if k == "l":
        return ".{ .rel = %s }" % p[1]
    if k == "z":
        idx = "" if p[3] == "-1" else ", .idx = %s" % p[3]
        return ".{ .z = .{ .id = %s, .et = .%s%s } }" % (p[1], p[2], idx)
    if k == "p":
        return ".{ .p = .{ .id = %s, .et = .%s, .q = .%s } }" % (p[1], p[2], p[3])
    if k == "m":
        base, ix, ixs, ext, extn, off, mode = p[1:]
        s = ".base = %s" % gp(base, "x")
        if ix != "-":
            s += ", .index = %s" % gp(ix, ixs)
        if ext != "-":
            s += ", .ext = .{ .op = .%s, .n = %s }" % (ext, extn)
        if off != "0":
            s += ", .off = %s" % off
        if mode != "off":
            s += ", .mode = .%s" % mode
        return ".{ .mem = .{ %s } }" % s
    raise ValueError(t)


def load():
    cases = []
    for line in open(CASES):
        if line.startswith("#") or not line.strip():
            continue
        kind, mn, ops, word, asm = line.rstrip("\n").split("|")
        cases.append((kind, mn, ops, word, asm))
    return cases


def mc_word(text):
    mc = os.environ.get("LLVM_MC", "llvm-mc")
    p = subprocess.run([mc, "-triple=aarch64", "-mattr=+all", "-show-encoding"], input=text + "\n", capture_output=True, text=True)
    for x in p.stdout.splitlines():
        if "encoding: [" in x:
            b = x.split("encoding: [")[1].split("]")[0].split(",")
            return "".join(reversed([y.strip()[2:].upper().zfill(2) for y in b]))
    return None


def verify(cases):
    bad = 0
    for kind, mn, ops, word, asm in cases:
        if kind == "llvm" and mc_word(asm) != word:
            print("llvm-mc disagrees:", asm, word)
            bad += 1
        if kind == "removed" and mc_word(asm) is not None:
            print("llvm-mc accepts a removed case:", asm)
            bad += 1
    return bad


def zstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    cases = load()
    if "--verify" in sys.argv:
        bad = verify(cases)
        if bad:
            sys.exit("%d cases disagree with llvm-mc" % bad)
    count = {k: sum(1 for c in cases if c[0] == k) for k in ("asmjit", "llvm", "removed")}
    out = [
        "//! GENERATED by scripts/gen_a64_table_tests.py from src/testdata/a64_table_cases.txt - do not edit.",
        "//! The LLVM-generated AArch64 table vs the AsmJit table it replaced: %d frozen AsmJit encodings," % count["asmjit"],
        "//! %d encodings checked with llvm-mc (LLVM 23.1.4), %d AsmJit-accepted forms LLVM rejects." % (count["llvm"], count["removed"]),
        'const std = @import("std");',
        'const a64 = @import("aarch64/a64.zig");',
        "",
        "fn check(expected: u32, comptime mn: a64.Mnemonic, ops: []const a64.Op, text: []const u8) u32 {",
        "    const w = a64.encodeMn(mn, ops) orelse {",
        '        std.debug.print("NoMatchingForm: {s}\\n", .{text});',
        "        return 1;",
        "    };",
        "    if (w == expected) return 0;",
        '    std.debug.print("encoding mismatch: {s}: want {X:0>8} got {X:0>8}\\n", .{ text, expected, w });',
        "    return 1;",
        "}",
        "",
        "fn removed(comptime mn: a64.Mnemonic, ops: []const a64.Op, text: []const u8) u32 {",
        "    const w = a64.encodeMn(mn, ops) orelse return 0;",
        '    std.debug.print("expected NoMatchingForm: {s}: got {X:0>8}\\n", .{ text, w });',
        "    return 1;",
        "}",
    ]
    for kind in ("asmjit", "llvm", "removed"):
        sel = [c for c in cases if c[0] == kind]
        for i in range(0, len(sel), CHUNK):
            out.append("")
            out.append('test "a64 table: %s cases (%d..%d)" {' % (kind, i, min(i + CHUNK, len(sel))))
            out.append("    var fails: u32 = 0;")
            for _, mn, ops, word, asm in sel[i:i + CHUNK]:
                zops = ", ".join(op(t) for t in ops.split(" ") if t)
                zops = "&.{ %s }" % zops if zops else "&.{}"
                if kind == "removed":
                    out.append('    fails += removed(.@"%s", %s, %s);' % (mn, zops, zstr(asm)))
                else:
                    out.append('    fails += check(0x%s, .@"%s", %s, %s);' % (word, mn, zops, zstr(asm)))
            out.append("    try std.testing.expectEqual(@as(u32, 0), fails);")
            out.append("}")
    open(OUT, "w").write("\n".join(out) + "\n")
    print("wrote", OUT, count)


if __name__ == "__main__":
    main()
