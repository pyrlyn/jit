#!/usr/bin/env python3
"""Differential fuzzing of the generated GP encoder against LLVM.

    python3 scripts/fuzz_gp.py [cases=5000] [seed=random] [--target=x86_64-macos]

Picks random forms from scripts/.gp_forms.json with random registers (all 16, incl. REX-only
8-bit), random memory (base/index/scale/disp8/disp32/no-base/RIP) and random immediates inside
each kind's range. LLVM (clang -c + objdump) produces the expected bytes; the cases are written to
src/gp_fuzz.zig and run with `zig build test -Dgp-fuzz=true`. The placeholder is restored after.
"""
import json, os, random, subprocess, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_gp_tests import GP, PTR, ZSZ, FIXED, ZK, rname, assemble

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PLACEHOLDER = open(os.path.join(ROOT, "src/gp_fuzz.zig")).read()
assert "Placeholder" in PLACEHOLDER, "src/gp_fuzz.zig is not the placeholder; git checkout it first"
RANGES = {"i8": (-128, 255), "s8": (-128, 127), "u8": (0, 255), "i16": (-32768, 65535), "u16": (0, 65535),
          "i32": (-2**31, 2**32 - 1), "s32": (-2**31, 2**31 - 1), "u32": (0, 2**32 - 1), "i64": (-2**63, 2**63 - 1)}
SZ = {0: "none", 8: "b", 16: "w", 32: "d", 64: "q"}


def rnd_imm(rng, k):
    if k == "one":
        return 1
    lo, hi = RANGES[k]
    return rng.choice([lo, hi, 0, -1 if lo < 0 else 1, rng.randint(lo, hi), rng.randint(max(lo, -200), min(hi, 200))])


def rnd_mem(rng, sz):
    pre = f"{PTR[sz]} ptr " if sz else ""
    kind = rng.random()
    disp = rng.choice([0, rng.randint(-128, 127), rng.randint(-2**31, 2**31 - 1)])
    if kind < 0.1:
        return f"gp.rip({disp}, .{SZ[sz]})", f"{pre}[rip{disp:+d}]"
    base = rng.choice(GP)
    idx = rng.choice([None] + [g for g in GP if g != "rsp"])
    sc = rng.choice([1, 2, 4, 8])
    if kind < 0.2 and idx:  # no base: [index*scale + disp32]
        z = f"x.Mem{{ .index = .{idx}, .scale = .x{sc}, .disp = {disp} }}"
        t = f"[{idx}*{sc}{disp:+d}]"
    elif idx:
        z = f"x.ptrIdx(.{base}, .{idx}, .x{sc}, {disp})"
        t = f"[{base}+{idx}*{sc}{disp:+d}]"
    else:
        z = f"x.ptr(.{base}, {disp})"
        t = f"[{base}{disp:+d}]"
    zf = f"gp.{ZSZ[sz]}({z})" if sz else f"gp.mem({z})"
    return zf, pre + t


def case(rng, mn, f):
    zs, ts = [], []
    for k in f["ops"]:
        if k in ("r8", "r16", "r32", "r64"):
            g, sz = rng.choice(GP), int(k[1:])
            zs.append(f"gp.r{sz}(.{g})")
            ts.append(rname(g, sz))
        elif k in ("m8", "m16", "m32", "m64", "m"):
            z, t = rnd_mem(rng, int(k[1:]) if k != "m" else 0)
            zs.append(z)
            ts.append(t)
        elif k in FIXED:
            g, sz = FIXED[k]
            zs.append(f"gp.r{sz}(.{g})")
            ts.append(rname(g, sz))
        else:
            v = rnd_imm(rng, k)
            zs.append(f"@as(i64, {v})")
            ts.append(str(v))
    return mn, zs, f"{mn} {', '.join(ts)}".strip()


def equivalent(ln):
    """Known, semantically identical deviations from LLVM (documented in ARCHITECTURE.md)."""
    if "int 3: expected cc, got cd03" in ln:
        return True  # explicit `int 3`; use int3() for the one-byte CC
    if "xchg rax, rax: expected 90, got 4890" in ln:
        return True  # both are a no-op on rax
    if "mismatch: and r" in ln and ", got " in ln:  # AsmJit: and r64, u32 -> and r32, imm32 (zero-extends)
        e, g = ln.split("expected ")[1].split(", got ")
        e, g = e.strip(), g.strip()
        if e.startswith("48") and g == e[2:]:
            return True
        return len(e) == len(g) and e[0] == "4" and e[1] in "89abcdef" and g[:2] == "4" + format(int(e[1], 16) - 8, "x") and e[2:] == g[2:]
    return False


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    extra = [a.replace("--target=", "-Dtarget=") for a in sys.argv[1:] if a.startswith("--target=")]
    n = int(args[0]) if args else 5000
    seed = int(args[1]) if len(args) > 1 else random.randrange(2**32)
    rng = random.Random(seed)
    fs = json.load(open(os.path.join(ROOT, "scripts/.gp_forms.json")))
    flat = [(mn, f) for mn in fs for f in fs[mn]]
    cases = [case(rng, *rng.choice(flat)) for _ in range(n)]
    got = assemble([c[2] for c in cases])
    out = [f"//! GENERATED by scripts/fuzz_gp.py, seed {seed}. Temporary.", 'const std = @import("std");',
           'const CodeBuffer = @import("core/code_buffer.zig").CodeBuffer;',
           "fn check(expected: []const u8, comptime mn: anytype, args: anytype, text: []const u8) u32 {",
           '    const gp = @import("x86_64/gp.zig");', "    var cb = CodeBuffer.init(std.testing.allocator);", "    defer cb.deinit();",
           '    gp.emit(&cb, mn, args) catch |e| { std.debug.print("FUZZ {s}: {s}\\n", .{ @errorName(e), text }); return 1; };',
           "    if (std.mem.eql(u8, expected, cb.code())) return 0;",
           '    std.debug.print("FUZZ mismatch: {s}: expected {x}, got {x}\\n", .{ text, expected, cb.code() });', "    return 1;", "}"]
    items = sorted(got.items())
    for ci in range(0, len(items), 400):
        out += [f'test "gp fuzz {ci}" {{', "    @setEvalBranchQuota(1_000_000);", '    const x = @import("x86_64/assembler.zig");',
                '    const gp = x.gp;', "    var fails: u32 = 0;"]
        for i, b in items[ci:ci + 400]:
            mn, zs, text = cases[i]
            m = f'@"{mn}"' if mn in ZK else mn
            out.append(f'    fails += check(&.{{ {", ".join(hex(v) for v in b)} }}, .{m}, .{{ {", ".join(zs)} }}, "{text}");')
        out += ["    _ = &x;", "    try std.testing.expectEqual(@as(u32, 0), fails);", "}"]
    path = os.path.join(ROOT, "src/gp_fuzz.zig")
    try:
        open(path, "w").write("\n".join(out) + "\n")
        r = subprocess.run(["mise", "exec", "--", "zig", "build", "test", "-Dgp-fuzz=true"] + extra, cwd=ROOT, capture_output=True, text=True)
        bad = sorted({ln.strip() for ln in r.stderr.splitlines() if "FUZZ" in ln and not equivalent(ln)})
        print("\n".join(bad[:50]))
        print(f"seed {seed}: {len(got)} cases accepted by LLVM ({n - len(got)} rejected), {len(bad)} failures, zig exit {r.returncode}")
        raw = any("FUZZ" in ln for ln in r.stderr.splitlines())
        if r.returncode and not raw:
            print(r.stderr[-3000:])
        rc = 1 if bad or (r.returncode and not raw) else 0
    finally:
        open(path, "w").write(PLACEHOLDER)
    sys.exit(rc)


if __name__ == "__main__":
    main()
