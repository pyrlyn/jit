//! Generate encoder tables from LLVM's target descriptions (Apache-2.0 WITH LLVM-exception).
//!
//!     zig build gen-tables -Dllvm-src=PATH/llvm-project [-Dllvm-tblgen=llvm-tblgen]
//!
//! The build step runs `llvm-tblgen --dump-json` over llvm/lib/Target/X86/X86.td and
//! llvm/lib/Target/AArch64/AArch64.td and passes the JSON here:
//!
//!     gen_tables x86 X86.json ROOT        writes ROOT/src/x86_64/gp_table.zig,
//!                                         ROOT/src/x86_64/isa.zig and ROOT/scripts/.gp_forms.json
//!     gen_tables a64 AArch64.json ROOT    writes ROOT/src/aarch64/isa.zig
//!
//! Pinned LLVM: llvmorg-23.1.4 (see docs/llvm-tables.md). Not needed for a normal build: the
//! generated tables are committed.
const std = @import("std");
const lj = @import("llvm_json.zig");
const x86_gp = @import("gen_x86_gp.zig");
const isa = @import("gen_isa.zig");

pub const llvm_tag = "llvmorg-23.1.4";

pub fn main(init: std.process.Init) !void {
    const a = init.arena.allocator();
    const io = init.io;
    const args = try init.minimal.args.toSlice(a);
    if (args.len != 4) {
        std.debug.print("usage: gen_tables x86|a64 TBLGEN.json ROOT\n", .{});
        std.process.exit(2);
    }
    const db = try lj.Db.load(a, io, args[2]);
    var root = try std.Io.Dir.cwd().openDir(io, args[3], .{});
    defer root.close(io);
    if (std.mem.eql(u8, args[1], "x86")) {
        const out = try x86_gp.render(a, db, header_gp);
        try root.createDirPath(io, "src/x86_64");
        try root.createDirPath(io, "scripts");
        try root.writeFile(io, .{ .sub_path = "src/x86_64/gp_table.zig", .data = out.zig });
        try root.writeFile(io, .{ .sub_path = "scripts/.gp_forms.json", .data = out.json });
        try root.writeFile(io, .{ .sub_path = "src/x86_64/isa.zig", .data = try isa.renderX86(a, db, header("X86", "x86_64/isa.zig")) });
    } else if (std.mem.eql(u8, args[1], "a64")) {
        try root.createDirPath(io, "src/aarch64");
        try root.writeFile(io, .{ .sub_path = "src/aarch64/isa.zig", .data = try isa.renderA64(a, db, header("AArch64", "aarch64/isa.zig")) });
    } else return error.UnknownTarget;
}

const header_gp =
    "// Generated by tools/gen_tables.zig (`zig build gen-tables`) from LLVM's X86 target description\n" ++
    "// (llvm/lib/Target/X86/*.td, llvm-project " ++ llvm_tag ++ ", Apache-2.0 WITH LLVM-exception;\n" ++
    "// see NOTICE). Do not edit.\n";

fn header(comptime target: []const u8, comptime file: []const u8) []const u8 {
    _ = file;
    return "//! Generated by tools/gen_tables.zig (`zig build gen-tables`) from LLVM's " ++ target ++ " target\n" ++
        "//! description (llvm/lib/Target/" ++ target ++ "/*.td, llvm-project " ++ llvm_tag ++ ",\n" ++
        "//! Apache-2.0 WITH LLVM-exception; see NOTICE). Do not edit.\n";
}
